let age = "Neeki"; //This is a string literal
let isStudent = true; //This is a boolean literal
let pi = 3.14; //This is a number literal
let name = "Alivce"; //This is a string literal
let nullValue = null; //This is a null literal
let undefinedValue; //This is an undefined literal


//typeof operator it will tell you the type of the value stored in the variable 
console.log( typeof age ); //string
console.log( typeof isStudent ); //boolean
console.log( typeof pi ); //number
console.log( typeof name ); //string
console.log( typeof nullValue ); //object 
console.log( typeof undefinedValue ); //undefined

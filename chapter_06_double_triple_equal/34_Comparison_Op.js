//comparison operators
//>,<,>=,<=,==,===,!=,!==

// =  -> assignment operator
// == -> equality operator (loose equality) compares values after type coercion
// === -> strict equality operator compares values without type coercion (also checks for type)

console.log( 3 > 5 ); // false  
//  (loose equality, type coercion occurs)
console.log( 3 < 4 ); // true
// (strict equality, no type coercion)
console.log( 4 >= 4 ); // 4>4 or 4==4 or gate 
console.log( 3 <= 4 ); // 3<4 or 3=4 false  
let x = 10;
x += 10; // x=x+10     += compound operators add the right operand to the left operand and assign the result to the left operand 
console.log( "Result:", x );

let y = 3;
y -= 2; // y=y-2     -= compound operators subtract the right operand from the left operand and assign the result to the left operand
console.log( "Result:", y );

let z = 5;
z *= 4; // z=z*4     *= compound operators multiply the left operand by the right operand and assign the result to the left operand
console.log( "Result:", z );

let a = 20;
a /= 5; // a=a/5     /= compound operators divide the left operand by the right operand and assign the result to the left operand
console.log( "Result:", a );

let a = 2;
a %= 2; // a=a%2     %= compound operators divide the left operand by the right operand and assign the remainder to the left operand
console.log( "Result:", a );